<#
.SYNOPSIS
    Creates langfuse\.env with a fresh random value for every Langfuse secret.

.DESCRIPTION
    Run it once, before the first `docker compose up`. It never prints a secret, and it
    refuses to replace an existing .env: the secrets are baked into the Langfuse volumes on
    first start, so new ones would lock Langfuse out of its own data. To start completely
    over, remove the volumes first (see docs\langfuse-lab\01-langfuse-setup.md), then run
    this again with -Force.

.EXAMPLE
    .\New-LangfuseEnv.ps1
#>
param([switch]$Force)

$ErrorActionPreference = 'Stop'
$envFile = Join-Path $PSScriptRoot '.env'

if ((Test-Path $envFile) -and -not $Force) {
    Write-Host "langfuse\.env already exists, so nothing was changed." -ForegroundColor Yellow
    Write-Host "Its secrets are already stored in the Langfuse volumes. Use -Force only after removing them."
    exit 0
}

# Hex only: it is safe inside a database URL and a Redis command line without escaping
function New-Secret {
    $bytes = New-Object byte[] 32
    $generator = [Security.Cryptography.RandomNumberGenerator]::Create()
    $generator.GetBytes($bytes)
    $generator.Dispose()
    return -join ($bytes | ForEach-Object { $_.ToString('x2') })
}

$postgresPassword = New-Secret
$minioPassword = New-Secret

$lines = @(
    '# Generated by New-LangfuseEnv.ps1. Never commit this file.'
    'LANGFUSE_VERSION=4.56.0'
    'NEXTAUTH_URL=http://localhost:3000'
    'TELEMETRY_ENABLED=false'
    "NEXTAUTH_SECRET=$(New-Secret)"
    "SALT=$(New-Secret)"
    "ENCRYPTION_KEY=$(New-Secret)"
    "POSTGRES_PASSWORD=$postgresPassword"
    "DATABASE_URL=postgresql://postgres:$postgresPassword@postgres:5432/postgres"
    "CLICKHOUSE_PASSWORD=$(New-Secret)"
    "REDIS_AUTH=$(New-Secret)"
    "MINIO_ROOT_PASSWORD=$minioPassword"
    "LANGFUSE_S3_EVENT_UPLOAD_SECRET_ACCESS_KEY=$minioPassword"
    "LANGFUSE_S3_MEDIA_UPLOAD_SECRET_ACCESS_KEY=$minioPassword"
    "LANGFUSE_S3_BATCH_EXPORT_SECRET_ACCESS_KEY=$minioPassword"
)

# UTF-8 without a byte-order mark. Windows PowerShell's Set-Content would add one, and
# Docker Compose would then read the first variable's name with the mark glued to it.
[IO.File]::WriteAllLines($envFile, $lines, (New-Object Text.UTF8Encoding $false))
Write-Host "Created langfuse\.env with new random secrets." -ForegroundColor Green
